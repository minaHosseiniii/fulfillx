CREATE TABLE deliveries (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            order_id BIGINT NOT NULL,

                            delivery_status VARCHAR(30) NOT NULL,

                            recipient_name VARCHAR(150) NOT NULL,
                            phone_number VARCHAR(30) NOT NULL,
                            province VARCHAR(100),
                            city VARCHAR(100) NOT NULL,
                            address_line VARCHAR(500) NOT NULL,
                            postal_code VARCHAR(20),

                            tracking_number VARCHAR(100),

                            shipped_at TIMESTAMP WITH TIME ZONE,
                            delivered_at TIMESTAMP WITH TIME ZONE,

                            failure_reason VARCHAR(500),

                            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                            updated_at TIMESTAMP WITH TIME ZONE,

                            created_by VARCHAR(255) NOT NULL,
                            updated_by VARCHAR(255),

                            CONSTRAINT uk_delivery_order_id
                                UNIQUE (order_id),

                            CONSTRAINT uk_delivery_tracking_number
                                UNIQUE (tracking_number),

                            CONSTRAINT chk_delivery_order_id_positive
                                CHECK (order_id > 0),

                            CONSTRAINT chk_delivery_status
                                CHECK (
                                    delivery_status IN (
                                                        'PENDING',
                                                        'PREPARING',
                                                        'READY_FOR_PICKUP',
                                                        'IN_TRANSIT',
                                                        'DELIVERED',
                                                        'FAILED',
                                                        'RETURNED',
                                                        'CANCELLED'
                                        )
                                    ),

                            CONSTRAINT chk_delivery_timestamps
                                CHECK (
                                    delivered_at IS NULL
                                        OR shipped_at IS NOT NULL
                                    )
);

CREATE INDEX idx_delivery_status
    ON deliveries (delivery_status);